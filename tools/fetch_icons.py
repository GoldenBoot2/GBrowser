import socket
socket.setdefaulttimeout(30)   # also covers stalled reads (a run hung for 20 min without it)


def fetch(url):
    # curl: Python's urlopen hung for 20+ minutes on this PC (name lookup is not covered by its timeouts)
    import subprocess
    for attempt in range(3):
        r = subprocess.run(['curl', '-sS', '-f', '--max-time', '30', '-A', 'Mozilla/5.0', url], capture_output=True)
        if r.returncode == 0:
            return r.stdout.decode('utf-8')
        if r.returncode == 22:   # HTTP error (404 ...)
            raise urllib.error.HTTPError(url, 404, 'not found', None, None)
    raise RuntimeError('download failed: ' + url)

def main():
    paths = {}
    for entry in ICONS:
        key, name, var = entry[:3]
        size = entry[3] if len(entry) > 3 else 24   # optical size (20 px files for small window buttons)
        f = name + ('_' + var if var else '') + '_%dpx.svg' % size
        try:
            svg = fetch(BASE.format(n=name, f=f))
        except Exception as e:
            sys.exit('failed %s: %s' % (f, e))
        ds = re.findall(r'\sd="([^"]+)"', svg)
        if len(ds) != 1 or 'viewBox="0 -960 960 960"' not in svg:
            sys.exit('unexpected svg for ' + f)
        paths[key] = (f, ds[0])
        print('ok', f, len(ds[0]))
    cs = ['// Generated by tools/fetch_icons.py from google/material-design-icons (Material Symbols Rounded,',
          '// 24 px, viewBox 0 -960 960 960). Do not edit by hand.',
          'namespace GBrowser', '{', '    internal static class IconData', '    {']
    js = ['// Generated by tools/fetch_icons.py (Material Symbols Rounded, viewBox 0 -960 960 960).',
          'window.GB_ICONS = {']
    for key, (f, d) in paths.items():
        cs.append('        public const string %s = "%s"; // %s' % (key, d, f))
        js.append('  %s: "%s",' % (key, d))
    cs += ['    }', '}', '']
    js += ['};', '']
    with open(os.path.join(ROOT, 'src', 'IconData.cs'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(cs))
    with open(os.path.join(ROOT, 'pages', 'icons.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(js))
    # verify: re-read both files and compare with the downloaded paths
    cs_txt = open(os.path.join(ROOT, 'src', 'IconData.cs'), encoding='utf-8').read()
    js_txt = open(os.path.join(ROOT, 'pages', 'icons.js'), encoding='utf-8').read()
    for key, (f, d) in paths.items():
        assert ('public const string %s = "%s";' % (key, d)) in cs_txt, key
        assert ('  %s: "%s",' % (key, d)) in js_txt, key
    cmds = set(re.findall(r'[A-Za-z]', ''.join(d for _, d in paths.values())))
    print('verified', len(paths), 'icons; path commands used:', ''.join(sorted(cmds)))

if __name__ == '__main__':
    main()
