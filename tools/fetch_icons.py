# Downloads the official Material Symbols Rounded SVGs (google/material-design-icons) used by GBrowser
# and writes their path data to src/IconData.cs (C#) and pages/icons.js (internal pages).
# Every path is copied by script and checked against the downloaded file afterwards.
# Run: python -I tools/fetch_icons.py
import os, re, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 'https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{f}'

# (key, icon name, file variant) - 24 px optical size, default weight
ICONS = [
    ('Back', 'arrow_back', ''), ('Forward', 'arrow_forward', ''), ('Refresh', 'refresh', ''),
    ('Close', 'close', ''), ('Add', 'add', ''), ('Home', 'home', ''), ('Star', 'star', ''),
    ('StarFill', 'star', 'fill1'), ('Extension', 'extension', ''), ('More', 'more_vert', ''),
    ('Bookmarks', 'bookmarks', ''), ('History', 'history', ''), ('Download', 'download', ''),
    ('Settings', 'settings', ''), ('Info', 'info', ''), ('Shield', 'shield', ''), ('Delete', 'delete', ''),
    ('Folder', 'folder_open', ''), ('Person', 'person', ''), ('Public', 'public', ''),
    ('Search', 'search', ''), ('Lock', 'lock', ''), ('Memory', 'memory', ''), ('Code', 'code', ''),
    ('OpenNew', 'open_in_new', ''), ('Tab', 'tab', ''), ('Bedtime', 'bedtime', ''),
    ('Language', 'language', ''), ('Verified', 'verified', ''), ('Tune', 'tune', ''),
    ('Fullscreen', 'fullscreen', ''), ('Print', 'print', ''), ('ZoomIn', 'zoom_in', ''),
    ('ZoomOut', 'zoom_out', ''), ('Find', 'find_in_page', ''), ('Upload', 'upload_file', ''),
    ('Restore', 'restore_page', ''), ('Cookie', 'cookie', ''), ('Block', 'block', ''),
    ('Volume', 'volume_up', ''), ('Stop', 'close', ''),
]

def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode('utf-8')

def main():
    paths = {}
    for key, name, var in ICONS:
        f = name + ('_' + var if var else '') + '_24px.svg'
        try:
            svg = fetch(BASE.format(n=name, f=f))
        except Exception as e:
            sys.exit('failed %s: %s' % (f, e))
        ds = re.findall(r'\sd="([^"]+)"', svg)
        if len(ds) != 1 or 'viewBox="0 -960 960 960"' not in svg:
            sys.exit('unexpected svg for ' + f)
        paths[key] = (f, ds[0])
        print('ok', f, len(ds[0]))
    cs = ['// Generated by tools/fetch_icons.py from google/material-design-icons (Material Symbols Rounded,',
          '// 24 px, viewBox 0 -960 960 960). Do not edit by hand.',
          'namespace GBrowser', '{', '    internal static class IconData', '    {']
    js = ['// Generated by tools/fetch_icons.py (Material Symbols Rounded, viewBox 0 -960 960 960).',
          'window.GB_ICONS = {']
    for key, (f, d) in paths.items():
        cs.append('        public const string %s = "%s"; // %s' % (key, d, f))
        js.append('  %s: "%s",' % (key, d))
    cs += ['    }', '}', '']
    js += ['};', '']
    with open(os.path.join(ROOT, 'src', 'IconData.cs'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(cs))
    with open(os.path.join(ROOT, 'pages', 'icons.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(js))
    # verify: re-read both files and compare with the downloaded paths
    cs_txt = open(os.path.join(ROOT, 'src', 'IconData.cs'), encoding='utf-8').read()
    js_txt = open(os.path.join(ROOT, 'pages', 'icons.js'), encoding='utf-8').read()
    for key, (f, d) in paths.items():
        assert ('public const string %s = "%s";' % (key, d)) in cs_txt, key
        assert ('  %s: "%s",' % (key, d)) in js_txt, key
    cmds = set(re.findall(r'[A-Za-z]', ''.join(d for _, d in paths.values())))
    print('verified', len(paths), 'icons; path commands used:', ''.join(sorted(cmds)))

if __name__ == '__main__':
    main()
